#!/usr/bin/env node
/**
 * Export the compiled contract ABIs into @cryptopay/shared so the API, indexer and
 * web app consume one frozen copy of the event/function surface (Phase 1 gate).
 *
 * Run after `forge build`:
 *   node scripts/export-abi.mjs
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'contracts', 'out');
const target = join(root, 'packages', 'shared', 'src', 'abi.ts');

const contracts = [
  { name: 'PaymentProcessor', file: 'PaymentProcessor.sol/PaymentProcessor.json', export: 'paymentProcessorAbi' },
  { name: 'TestUSDC', file: 'TestUSDC.sol/TestUSDC.json', export: 'testUsdcAbi' },
];

function loadAbi(entry) {
  const path = join(outDir, entry.file);
  if (!existsSync(path)) {
    throw new Error(`Missing artifact ${path}. Run "forge build" in contracts/ first.`);
  }
  const artifact = JSON.parse(readFileSync(path, 'utf8'));
  if (!Array.isArray(artifact.abi)) {
    throw new Error(`Artifact ${path} has no ABI array`);
  }
  return artifact.abi;
}

const header = `// Generated by scripts/export-abi.mjs. Do not edit by hand.\n// Source: contracts/out (Foundry). Regenerate with "npm run contracts:export-abi".\n\n`;

const body = contracts
  .map((entry) => {
    const abi = loadAbi(entry);
    const json = JSON.stringify(abi, null, 2);
    return `/** ABI for ${entry.name}. */\nexport const ${entry.export} = ${json} as const;\n`;
  })
  .join('\n');

mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, header + body, 'utf8');
console.log(`Wrote ${contracts.length} ABIs to ${target}`);
